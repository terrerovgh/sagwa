typedef struct {
    bool valid;
    float value;
    int64_t at_us;
} reading_t;

// Decode 7 bytes from LTR-553ALS-WA registers 0x88..0x8E:
// raw[0..1] = ALS_CH1, raw[2..3] = ALS_CH0, raw[4] = ALS_PS_STATUS, raw[5..6] = PS_DATA.
static bool ltr553_decode(const uint8_t raw[7], float *lux_out, int *prox_out) {
    uint16_t ch1 = (uint16_t)(raw[0] | (raw[1] << 8));
    uint16_t ch0 = (uint16_t)(raw[2] | (raw[3] << 8));
    int ps = (int)(raw[5] | ((raw[6] & 0x07) << 8));
    float lux = 0.0f;
    uint32_t sum = (uint32_t)ch0 + (uint32_t)ch1;
    if (sum > 0) {
        float ratio = (float)ch1 / (float)sum;
        if (ratio < 0.45f) {
            lux = 1.7743f * (float)ch0 + 1.1059f * (float)ch1;
        } else if (ratio < 0.64f && 4.2785f * (float)ch0 > 1.9548f * (float)ch1) {
            lux = 4.2785f * (float)ch0 - 1.9548f * (float)ch1;
        } else if (ratio < 0.85f) {
            lux = 0.5926f * (float)ch0 + 0.1185f * (float)ch1;
        }
    }
    if (!isfinite(lux) || lux < 0.0f) lux = 0.0f;
    *lux_out = lux;
    *prox_out = ps;
    return true;
}

// Decode 12 bytes from BMI270 registers 0x0C..0x17 (accel + gyro) and 2 bytes from 0x22..0x23 (temp).
static bool bmi270_decode(const uint8_t raw_imu[12], const uint8_t raw_temp[2], float temp_offset_c,
                          float *ax, float *ay, float *az,
                          float *gx, float *gy, float *gz,
                          float *tilt_deg, float *temp_c, bool *temp_ok) {
    int16_t rax = (int16_t)((uint16_t)raw_imu[0] | ((uint16_t)raw_imu[1] << 8));
    int16_t ray = (int16_t)((uint16_t)raw_imu[2] | ((uint16_t)raw_imu[3] << 8));
    int16_t raz = (int16_t)((uint16_t)raw_imu[4] | ((uint16_t)raw_imu[5] << 8));
    int16_t rgx = (int16_t)((uint16_t)raw_imu[6] | ((uint16_t)raw_imu[7] << 8));
    int16_t rgy = (int16_t)((uint16_t)raw_imu[8] | ((uint16_t)raw_imu[9] << 8));
    int16_t rgz = (int16_t)((uint16_t)raw_imu[10] | ((uint16_t)raw_imu[11] << 8));

    const float a_scale = 8.0f / 32768.0f;
    const float g_scale = 2000.0f / 32768.0f;
    *ax = (float)rax * a_scale;
    *ay = (float)ray * a_scale;
    *az = (float)raz * a_scale;
    *gx = (float)rgx * g_scale;
    *gy = (float)rgy * g_scale;
    *gz = (float)rgz * g_scale;

    float norm = sqrtf((*ax) * (*ax) + (*ay) * (*ay) + (*az) * (*az));
    if (norm > 0.05f) {
        float cz = (*az) / norm;
        if (cz > 1.0f) cz = 1.0f;
        if (cz < -1.0f) cz = -1.0f;
        *tilt_deg = acosf(cz) * (180.0f / 3.14159265f);
    } else {
        *tilt_deg = 0.0f;
    }

    int16_t rt = (int16_t)((uint16_t)raw_temp[0] | ((uint16_t)raw_temp[1] << 8));
    if (rt != (int16_t)0x8000) {
        *temp_c = 23.0f + ((float)rt / 512.0f) + temp_offset_c;
        *temp_ok = isfinite(*temp_c);
    } else {
        *temp_c = 0.0f;
        *temp_ok = false;
    }
    return isfinite(*ax) && isfinite(*ay) && isfinite(*az);
}

static cJSON *readings_result(const reading_t *readings, int64_t now_us) {
    cJSON *result = cJSON_CreateObject();
    cJSON *payload = cJSON_CreateObject();
    if (!result || !payload) {
        cJSON_Delete(result);
        cJSON_Delete(payload);
        return NULL;
    }
    bool any = false;
    for (int i = 0; i < SENSOR_COUNT; i++) {
        const reading_t *r = &readings[i];
        if (!r->valid || now_us - r->at_us > STALE_US) {
            cJSON_AddNullToObject(payload, SENSORS[i].name);
            continue;
        }
        cJSON *sensor = cJSON_AddObjectToObject(payload, SENSORS[i].name);
        double scale = pow(10, SENSORS[i].decimals);
        cJSON_AddNumberToObject(sensor, "value", round(r->value * scale) / scale);
        cJSON_AddStringToObject(sensor, "unit", SENSORS[i].unit);
        cJSON_AddNumberToObject(sensor, "age_s", (double)((now_us - r->at_us) / 1000000));
        any = true;
    }
    if (!any) {
        cJSON_Delete(payload);
        cJSON_AddBoolToObject(result, "ok", false);
        cJSON *error = cJSON_AddObjectToObject(result, "error");
        cJSON_AddStringToObject(error, "code", "no_readings");
        cJSON_AddStringToObject(error, "message",
                                "no sensor readings from the CoreS3 LTR-553 or BMI270");
        return result;
    }
    cJSON_AddBoolToObject(result, "ok", true);
    cJSON_AddItemToObject(result, "payload", payload);
    return result;
}

